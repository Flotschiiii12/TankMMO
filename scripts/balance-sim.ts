/**
 * Combat balance report built from the real simulation:  npm run balance-sim [-- --seeds 8 --out docs/BALANCE_REPORT.md --quick]
 * Level-matched characters in standard gear (see gearPolicy in balanceLib.ts) duel every enemy archetype, elites, bosses,
 * gates and each other. Targets (docs/GDD.md): normal enemy 5-15 s, elite 30-60 s, boss 3-8 min for a group, PvP 20-40 s.
 */
import { writeFileSync } from 'node:fs';
import { BOSS_CATALOG, CLASSES, DUNGEONS, FAMILIES, NORMAL_ENEMIES, TIER_LEVELS, Build, duelPve, duelPvp, groupVsBoss, groupVsGate } from './balanceLib.ts';

const arg = (n: string, d: string) => { const i = process.argv.indexOf(`--${n}`); return i >= 0 ? process.argv[i + 1] : d; };
const quick = process.argv.includes('--quick');
const SEEDS = Array.from({ length: Number(arg('seeds', quick ? '3' : '8')) }, (_, i) => i + 1);
const OUT = arg('out', '');
export const TARGETS = { normal: [5, 15], elite: [30, 60], boss: [180, 480], pvp: [20, 40] } as const;

const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : NaN);
const f1 = (x: number) => (Number.isFinite(x) ? x.toFixed(1) : '-');
const mark = (v: number, [lo, hi]: readonly number[]) => (!Number.isFinite(v) ? '' : v < lo ? '▼' : v > hi ? '▲' : '');

/** TTK (s) over won fights, win rate and mean health left of the player. */
function pveCell(b: Build, enemies: readonly string[], elite = false) {
  const t: number[] = []; let wins = 0, n = 0, left = 0;
  for (const e of enemies) for (const seed of SEEDS) { const r = duelPve(b, e, { elite, seed }); n++; left += r.hullLeft; if (r.win) { wins++; t.push(r.seconds); } }
  return { ttk: mean(t), win: wins / n, left: left / n };
}

const out: string[] = [];
const P = (s = '') => out.push(s);
const tierCols = Array.from({ length: 10 }, (_, i) => `T${i + 1}`);
const table = (head: string[], rows: string[][]) => { P(`| ${head.join(' | ')} |`); P(`|${head.map(() => '---').join('|')}|`); for (const r of rows) P(`| ${r.join(' | ')} |`); P(); };

P('# Combat balance report');
P();
P(`Generated by \`npm run balance-sim\` (${SEEDS.length} seeds per cell). Level-matched characters (tier ${TIER_LEVELS.map((l, i) => `T${i + 1}=L${l}`).join(', ')}) in the standard gear of \`gearPolicy\`, class cannon unless stated; the player closes to ~120 units (machine-gun range) and fires with auto-fire; enemies use the real AI.`);
P('Time-to-kill is the mean over won fights, in seconds. ▼ = below the target band, ▲ = above it. "W" is the win rate.');
P();

// ---------------------------------------------------------------- normal enemies
P(`## 1. Normal enemies, class x tier (target ${TARGETS.normal.join('-')} s)`);
P(`Mean over ${NORMAL_ENEMIES.length} archetypes (${NORMAL_ENEMIES.join(', ')}).`);
P();
const normalGrid: Record<string, number[]> = {};
{
  const rows = CLASSES.map((cls) => {
    normalGrid[cls] = [];
    return [cls, ...tierCols.map((_, i) => { const c = pveCell({ cls, tier: i + 1 }, NORMAL_ENEMIES); normalGrid[cls].push(c.ttk); return `${f1(c.ttk)}${mark(c.ttk, TARGETS.normal)} W${Math.round(c.win * 100)}`; })];
  });
  table(['class', ...tierCols], rows);
}
const allNormal = CLASSES.flatMap((c) => normalGrid[c]).filter(Number.isFinite);
P(`Overall: mean ${f1(mean(allNormal))} s, min ${f1(Math.min(...allNormal))} s, max ${f1(Math.max(...allNormal))} s; cells in band: ${allNormal.filter((v) => v >= TARGETS.normal[0] && v <= TARGETS.normal[1]).length}/${allNormal.length}.`);
P();

// ---------------------------------------------------------------- weapon families
P('## 2. Weapon families (medium class), normal enemies');
P();
{
  const rows = FAMILIES.map((family) => [family, ...tierCols.map((_, i) => { const c = pveCell({ cls: 'medium', tier: i + 1, family }, NORMAL_ENEMIES); return `${f1(c.ttk)}${mark(c.ttk, TARGETS.normal)} W${Math.round(c.win * 100)}`; })]);
  table(['family', ...tierCols], rows);
}

// ---------------------------------------------------------------- per archetype
P('## 3. Each archetype, medium class');
P();
{
  const tiers = [1, 3, 5, 7, 10];
  const rows = NORMAL_ENEMIES.map((e) => [e, ...tiers.map((t) => { const c = pveCell({ cls: 'medium', tier: t }, [e]); return `${f1(c.ttk)}${mark(c.ttk, TARGETS.normal)} W${Math.round(c.win * 100)}`; })]);
  table(['archetype', ...tiers.map((t) => `T${t}`)], rows);
}

// ---------------------------------------------------------------- elites
P(`## 4. Elite enemies, class x tier (target ${TARGETS.elite.join('-')} s)`);
P('Elite gunner truck and elite scout buggy (5.5x hull, 1.1x damage).');
P();
const eliteGrid: number[] = [];
{
  const rows = CLASSES.map((cls) => [cls, ...tierCols.map((_, i) => { const c = pveCell({ cls, tier: i + 1 }, ['gunner_truck', 'scout_buggy'], true); eliteGrid.push(c.ttk); return `${f1(c.ttk)}${mark(c.ttk, TARGETS.elite)} W${Math.round(c.win * 100)}`; })]);
  table(['class', ...tierCols], rows);
}
const el = eliteGrid.filter(Number.isFinite);
P(`Overall: mean ${f1(mean(el))} s, cells in band: ${el.filter((v) => v >= TARGETS.elite[0] && v <= TARGETS.elite[1]).length}/${el.length}.`);
P();

// ---------------------------------------------------------------- PvP
P(`## 5. PvP, equal tier (target ${TARGETS.pvp.join('-')} s)`);
P('Win rate of the row class against the column class (both start 450 units apart; each pairing is played from both sides). Last columns: overall win rate and mean duel length.');
P();
const pvpOverall: Record<string, number[]> = Object.fromEntries(CLASSES.map((c) => [c, []]));
const pvpDur: number[] = [];
for (const tier of [1, 4, 7, 10]) {
  P(`### Tier ${tier}`);
  P();
  const rows = CLASSES.map((a) => {
    let w = 0, n = 0; const dur: number[] = [];
    const cells = CLASSES.map((b) => {
      let wins = 0, games = 0;
      for (const seed of SEEDS) {
        const r1 = duelPvp({ cls: a, tier }, { cls: b, tier }, seed); games++; wins += r1.win ? 1 : 0; dur.push(r1.seconds);
        const r2 = duelPvp({ cls: b, tier }, { cls: a, tier }, seed); games++; wins += r2.win || r2.timedOut ? 0 : 1; // a was the second player
      }
      if (a !== b) { w += wins; n += games; }
      return `${Math.round((wins / games) * 100)}%`;
    });
    pvpOverall[a].push(w / n); pvpDur.push(...dur);
    return [a, ...cells, `${Math.round((w / n) * 100)}%`, `${f1(mean(dur))}${mark(mean(dur), TARGETS.pvp)}`];
  });
  table(['row \\ col', ...CLASSES, 'overall', 'mean s'], rows);
}
const classRates = CLASSES.map((c) => ({ c, r: mean(pvpOverall[c]) }));
const best = classRates.reduce((a, b) => (b.r > a.r ? b : a)); const worst = classRates.reduce((a, b) => (b.r < a.r ? b : a));
P(`Class spread (cross-class PvP win rate): best **${best.c} ${Math.round(best.r * 100)}%**, worst **${worst.c} ${Math.round(worst.r * 100)}%**, ratio ${(best.r / Math.max(0.01, worst.r)).toFixed(2)}. Mean duel length ${f1(mean(pvpDur))} s.`);
P();
P('### Weapon families in PvP (medium class, tier 5, win rate of row vs column)');
P();
{
  const rows = FAMILIES.map((a) => {
    let w = 0, n = 0;
    const cells = FAMILIES.map((b) => {
      let wins = 0, games = 0;
      for (const seed of SEEDS) {
        const r1 = duelPvp({ cls: 'medium', tier: 5, family: a }, { cls: 'medium', tier: 5, family: b }, seed); games++; wins += r1.win ? 1 : 0;
        const r2 = duelPvp({ cls: 'medium', tier: 5, family: b }, { cls: 'medium', tier: 5, family: a }, seed); games++; wins += r2.win || r2.timedOut ? 0 : 1;
      }
      if (a !== b) { w += wins; n += games; }
      return `${Math.round((wins / games) * 100)}%`;
    });
    return [a, ...cells, `${Math.round((w / n) * 100)}%`];
  });
  table(['row \\ col', ...FAMILIES, 'overall'], rows);
}

// ---------------------------------------------------------------- bosses
P(`## 6. Bosses and gates, party of 4 (target ${TARGETS.boss[0] / 60}-${TARGETS.boss[1] / 60} min)`);
P('Party: heavy, medium, artillery, support at the boss level (best tier available, standard gear).');
P();
const tierForLevel = (lvl: number) => { let t = 1; TIER_LEVELS.forEach((l, i) => { if (lvl >= l) t = i + 1; }); return t; };
const party = (lvl: number): Build[] => (['heavy', 'medium', 'artillery', 'support'] as const).map((cls) => ({ cls, tier: tierForLevel(lvl), level: lvl }));
const bossRows: string[][] = []; const bossTimes: number[] = [];
for (const b of BOSS_CATALOG) {
  const rs = SEEDS.map((seed) => groupVsBoss(b.id, party(b.level), seed));
  const win = rs.filter((r) => r.win);
  const t = mean(win.map((r) => r.seconds)); if (Number.isFinite(t)) bossTimes.push(t);
  bossRows.push([b.name, b.type, String(b.level), `${f1(t / 60)} min${mark(t, TARGETS.boss)}`, `${Math.round((win.length / rs.length) * 100)}%`, `${Math.round(mean(rs.map((r) => r.hullLeft)) * 100)}%`]);
}
table(['boss', 'type', 'level', 'time to kill', 'W', 'party health left'], bossRows);
P('### Gates (full run: waves + boss, party of 4)');
P();
const gateRows: string[][] = [];
for (const d of DUNGEONS) {
  const rs = SEEDS.slice(0, Math.max(2, Math.ceil(SEEDS.length / 2))).map((seed) => groupVsGate(d.id, party(d.recommendedLevel), seed));
  const win = rs.filter((r) => r.win);
  gateRows.push([d.name, String(d.recommendedLevel), `${f1(mean(win.map((r) => r.seconds)) / 60)} min`, `${Math.round((win.length / rs.length) * 100)}%`, `${Math.round(mean(rs.map((r) => r.hullLeft)) * 100)}%`, `${d.timeLimitSeconds / 60} min`]);
}
table(['gate', 'level', 'clear time', 'W', 'party health left', 'limit'], gateRows);

const text = out.join('\n') + '\n';
if (OUT) { writeFileSync(OUT, text); console.log(`wrote ${OUT}`); } else console.log(text);
